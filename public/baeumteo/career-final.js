// 인원에서 파생되는 모든 수치. 인원이 바뀌면 여기서 한꺼번에 바뀐다.
export function derive(setting = {}) {
  const s = { ...DEFAULT_SETTING, ...setting };
  const N = Math.min(50, Math.max(20, Number(s.people) || DEFAULT_SETTING.people));
  const own = Math.round(N * 0.33);
  const p1 = Math.round(N * 0.38);
  const p2 = N - own - p1;
  const C = classesFor('career', N);
  const sizes = Array.from({ length: C }, (_, i) => Math.floor(N / C) + (i < N % C ? 1 : 0));
  // 학년별 인원(중2·중3·고1·고2)을 학년 순으로 반에 채운다 → 반마다 인접 학년이 만난다.
  const grade = [Math.round(N * 0.24), Math.round(N * 0.29), Math.round(N * 0.26)];
  grade.push(N - grade[0] - grade[1] - grade[2]);
  const gradeNames = ['중학교 2학년', '중학교 3학년', '고등학교 1학년', '고등학교 2학년'];
  const pool = grade.flatMap((count, g) => Array(count).fill(g));
  let at = 0;
  const classes = sizes.map(size => {
    const members = pool.slice(at, at + size);
    at += size;
    const comp = grade.map((_, g) => members.filter(m => m === g).length);
    return { size, comp, text: comp.map((c, g) => (c ? `${gradeNames[g]} ${c}명` : '')).filter(Boolean).join(' · ') };
  });
  const low = Math.round(N * 0.69);
  const migrant = Math.round(N * 0.12);
  const referred = N - low - migrant;
  const mentors = Math.ceil(N / 7);
  const budget = budgetFor('career', N, { cap: 25_000_000 });
  const meetings = meetingsOf('career');
  const months = META.career.educationMonths;
  const attend = Math.ceil(N * 0.85);
  const split = (shares) => { const a = shares.slice(0, -1).map(x => Math.round(N * x)); return [...a, N - a.reduce((x, y) => x + y, 0)]; };
  const region = split([0.45, 0.33, 0]);        // 월곡동 · 우산동 · 신창동
  const housing = split([0.43, 0.33, 0]);       // 임대아파트 · 월세 다가구·원룸 · 자가·전세
  const jobs = split([0.38, 0.33, 0.17, 0]);    // 제조·물류 비정규 · 음식·돌봄 서비스 · 일용·단기 · 그 밖
  return { region, housing, jobs, s, N, own, p1, p2, C, sizes, classes, grade, gradeNames, low, migrant, referred, mentors, budget, meetings, months, attend,
    low1: Math.round(low * 0.41), low2: low - Math.round(low * 0.41), single: Math.round(N * 0.26), grand: Math.max(1, Math.round(N * 0.07)), dual: Math.round(N * 0.57), disabled: Math.max(1, Math.round(N * 0.02)),
    sessions: sessionTotal('career'), interviews: N * 2, wardCount: Math.round(N * 0.45) };
}

