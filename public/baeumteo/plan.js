const pending = slot => `〔${slot.role.replace(/^참여기관\s*|^협력\s*/, '')} 섭외 중〕`;
export function slotName(slot, input = {}) { return String(input.partners?.[slot.key] || '').trim() || pending(slot); }
export function leadName(input = {}) { return String(input.lead || '').trim() || '〔대표기관 선정 중〕'; }
const won = n => `${Math.round(n / 10_000).toLocaleString('ko-KR')}만 원`;

// 연합 기관(대표 + 이름이 들어온 참여기관) 수. 이주배경 유형은 5곳 이상이면 한도가 오른다.
export function unionSize(project, input = {}) {
  return (String(input.lead || '').trim() ? 1 : 0) + project.slots.filter(slot => String(input.partners?.[slot.key] || '').trim()).length;
}
export function capOf(project, input = {}) {
  return project.capUnion && unionSize(project, input) >= project.unionMin ? project.capUnion : project.cap;
}
export function people(project, input = {}) { return Math.max(FUND.minPeople, Number(input.people) || project.people); }
export function budgetRows(project, input = {}) {
  const cap = capOf(project, input);
  const rows = project.budget.map(([name, pct]) => [name, Math.round(cap * pct / 100 / 10_000) * 10_000]);
  const diff = cap - rows.reduce((sum, row) => sum + row[1], 0);
  rows[0][1] += diff; // 반올림 차이는 첫 비목(강사비)이 받는다
  return rows;
}

