// 돈 드는 호출을 다시 할 것인가 (23-11에서 설계 하나로 시작, 23-17에서 모두 합침).
//
// 실제로 났던 일: 막고 있던 것이 `state.busy` 하나뿐이라 **도는 동안만** 막혔다.
// 끝나고 나서 같은 단추를 다시 누르면 같은 입력으로 또 나갔다. 호출 하나가 77~404원이다.
//
// 판정은 셋만 본다.
//   redo         — 부른 쪽이 「다시 만들라」는 뜻인가 (설계 다시 만들기 · 실행계약서 충돌 반영 · 재검토)
//   hasResult    — 이미 만들어 둔 결과가 있는가
//   inputChanged — 그 결과를 만들 때와 입력이 달라졌는가
//
// 「달라졌는가」를 무엇으로 보는지는 자리마다 다르다 — 설계는 공고가 바뀌었는지, 나머지는
// 보낼 것을 통째로 SHA-256으로 찍어 견준다. 그 판단은 부르는 쪽이 하고, 여기서는 셋만 셈한다.
export function shouldRunAgain({ redo = false, hasResult = false, inputChanged = false } = {}) {
  // 「다시 만들라」가 뜻인 자리는 언제나 다시 만든다.
  if (redo) return true;
  // 만들어 둔 것이 없으면 만든다. 첫 호출을 막지 않는다.
  if (!hasResult) return true;
  // 있는데 입력이 그대로면 그 결과가 그대로 맞다. 다시 부르지 않는다.
  return inputChanged;
}
