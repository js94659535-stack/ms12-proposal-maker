// 설계를 다시 만들 것인가 (23-11).
//
// 실제로 났던 일: 「선택 완료 · 다음 단계」를 누르고 끝난 뒤 한 번 더 눌렀더니 공고 분석이 다시 돌았다.
// AI 호출이라 누를 때마다 돈이 든다. 막고 있던 것은 `state.busy` 하나뿐이라 「도는 동안」만 막혔고,
// 끝나고 나면 아무것도 막지 않았다. 게다가 두 번째 호출은 시작하면서 앞서 만든 설계를 지우고 시작한다.
//
// 판정을 따로 두는 까닭. 부르는 자리가 여섯이고 그중 둘은 「다시 만들라」가 뜻이다.
// 함수 안에 조건을 묻어 두면 어느 자리가 어느 뜻이었는지 다음에 알 수 없다.
export function shouldRunDesign({ redo = false, hasMaster = false, noticeChanged = false } = {}) {
  // 「설계 다시 만들기」·실행계약서 충돌 반영은 다시 만드는 것이 뜻이다.
  if (redo) return true;
  // 만들어 둔 것이 없으면 만든다.
  if (!hasMaster) return true;
  // 공고가 바뀌었으면 앞 공고의 설계를 쓸 수 없다. 그때는 다시 만든다.
  return noticeChanged;
}
