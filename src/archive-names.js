// 보관함 이름을 짓는 단 한 곳.
//
// 실제로 났던 일: 같은 보관함이 여섯 이름으로 불렸다. 「계획서보관함에서 불러오기」는 기관을
// 불러오는 버튼이었고, 「계획서보관함 목록」·「계획서 다시 불러오기」·「계획서보관함 계획서」는
// 모두 계획서 목록을 가져오는 같은 일이었다. 이름이 화면마다 그때그때 붙은 탓이다.
//
// 규칙은 둘이다.
//   ① 보관함은 담는 것으로 부른다 — 공고보관함·계획서보관함·기관보관함.
//   ② 하는 일은 셋뿐이다 — 열기(보관함 화면으로 간다) · 불러오기(지금 화면으로 목록을 가져온다) · 저장.
// 이름을 새로 지어야 할 것 같으면 규칙이 모자란 것이므로 여기를 고친다.
export const BOX = Object.freeze({ notice: '공고보관함', proposal: '계획서보관함', org: '기관보관함', verified: '계획서 검증보관함' });

export const openBox = kind => `${BOX[kind]} 열기`;
export const loadFrom = kind => `${BOX[kind]}에서 불러오기`;
export const saveTo = kind => `${BOX[kind]}에 저장`;
